function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function writeJson(filePath, data) {
  fs.writeFileSync(filePath, `${JSON.stringify(data, null, 2)}\n`, "utf8");
}

function iso(hoursAgo) {
  return new Date(Date.now() - hoursAgo * 60 * 60 * 1000).toISOString();
}

function gcxProfile(data) {
  return data.profiles.find((profile) => profile.id === "profile-gcx-member") || data.profiles[0] || {};
}

function articlePost(story, index, profile) {
  const url = `article.html?id=${story.id}`;
  const category = story.category === "Pokemon" || /pokemon/i.test(story.title) ? "Pokemon" : index % 3 === 0 ? "GCX" : "Gaming";
  return normalizeSocialPostDraft({
    id: `post-social-gcx-article-${slug(story.id)}`,
    postType: "gcx_news_share",
    author: "GCX Newsroom",
    handle: "@gcxnewsroom",
    profileId: profile.id,
    category,
    title: story.title,
    body: story.excerpt || story.metaDescription || "GCX has a new newsroom story ready for discussion.",
    linkUrl: url,
    canonicalUrl: url,
    sourceName: "GCX Newsroom",
    sourceUrl: url,
    sourceType: "gcx",
    imageUrl: story.heroImage || story.imageUrl || "",
    imageAlt: story.heroImageAlt || story.title,
    linkPreview: {
      url,
      kind: "gcx-news",
      title: story.title,
      description: story.excerpt || story.metaDescription || "",
      imageUrl: story.heroImage || story.imageUrl || "",
      sourceLabel: "GCX Newsroom",
    },
    tags: ["GCX", ...(story.tags || []).slice(0, 4)],
    createdAt: iso(index + 1),
    status: "published",
    likes: 0,
    reactions: { like: 0, hype: 0, want: 0, trade: 0, watch: 0 },
    comments: 0,
    reports: 0,
    duplicateKey: "",
  }, { profileId: profile.id });
}

function basePost(fields, index, profile) {
  return normalizeSocialPostDraft({
    id: `post-social-${slug(fields.title)}`,
    author: fields.author || "GCX Social",
    handle: fields.handle || "@gcxsocial",
    profileId: fields.profileId || profile.id,
    category: fields.category || "Community",
    postType: fields.postType || "community_post",
    title: fields.title,
    body: fields.body,
    linkUrl: fields.linkUrl || "",
    canonicalUrl: fields.canonicalUrl || fields.linkUrl || "",
    sourceName: fields.sourceName || "",
    sourceUrl: fields.sourceUrl || fields.linkUrl || "",
    sourceType: fields.sourceType || "",
    externalPostId: fields.externalPostId || "",
    platform: fields.platform || "",
    mediaType: fields.mediaType || "",
    embedUrl: fields.embedUrl || "",
    watchUrl: fields.watchUrl || fields.linkUrl || "",
    imageUrl: fields.imageUrl || "",
    imageAlt: fields.imageAlt || fields.title,
    topic: fields.topic || "",
    tags: fields.tags || [],
    linkPreview: fields.linkPreview || (fields.linkUrl ? {
      url: fields.linkUrl,
      kind: fields.sourceType || "external",
      title: fields.previewTitle || fields.title,
      description: fields.previewDescription || fields.body,
      imageUrl: fields.previewImageUrl || fields.imageUrl || "",
      sourceLabel: fields.sourceName || "Source",
    } : null),
    createdAt: iso(index + 10),
    scheduledAt: fields.scheduledAt || "",
    status: "published",
    markedStale: Boolean(fields.markedStale),
    editorialPinned: Boolean(fields.editorialPinned),
    editorialPriority: Number(fields.editorialPriority || 0),
    likes: 0,
    reactions: { like: 0, hype: 0, want: 0, trade: 0, watch: 0 },
    comments: 0,
    reports: 0,
  }, { profileId: profile.id });
}

function seedTopics(data) {
  const topics = [
    { id: "topic-gcx-news", label: "GCX News", keywords: ["gcx", "newsroom", "article", "hub"] },
    { id: "topic-pokemon-tcg", label: "Pokemon TCG", keywords: ["pokemon", "tcg", "pikachu", "card", "collector"] },
    { id: "topic-streaming", label: "Streaming", keywords: ["stream", "twitch", "youtube", "creator", "spotlight"] },
    { id: "topic-trailers", label: "Trailers", keywords: ["trailer", "showcase", "video", "watch"] },
  ];
  const existing = new Set((data.topics || []).map((topic) => topic.id));
  data.topics = [...(data.topics || []), ...topics.filter((topic) => !existing.has(topic.id))];
}

